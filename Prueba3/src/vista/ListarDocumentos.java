    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            modelo.removeAllElements();
            LibroDAO daoL = new LibroDAO();
            RevistaDAO daoR = new RevistaDAO();
            List<Libro> listarLibros = daoL.listar();
            List<Revista> listaRevistas = daoR.listar();
            
            for(Libro x : listarLibros) {
                modelo.addElement(x.imprimir());
            }
            
            for(Revista i : listaRevistas){
                modelo.addElement(i.imprimir());
                //modelo.addElement("REVISTA : Código " + i.getCodigo() + " Titulo " + i.getTitulo());
            }
            
           
        } catch (Exception e) {
        }
    }//GEN-LAST:event_jButton1ActionPerformed


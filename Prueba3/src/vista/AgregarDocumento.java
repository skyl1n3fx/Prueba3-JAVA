    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        int index = cboTipoDocumento.getSelectedIndex();
        if (index == 1) {
            try {
                // Es un LIBRO
                boolean prestamo = false;
                LibroDAO dao = new LibroDAO();
                if (rbtnSi.isSelected()) {
                    prestamo = true;
                }
                Libro libro = new Libro(prestamo, Integer.parseInt(txtCodigo.getText()), txtTitulo.getText(), txtAutor.getText(), txtEditorial.getText(), txtAnio.getText());
                if (dao.agregar(libro)) {
                    mensaje("Libro agregado con éxito!");
                } else {
                    mensaje("No se pudo agregar el libro");
                }
            } catch (Exception e) {
                mensaje("Ingrese datos válidos");
            }
        } else if (index == 2) {
            try {
                // ES una revista
                int mesID = cboMes.getSelectedIndex();
                RevistaDAO daoR = new RevistaDAO();
                Mes mes = new Mes(mesID);
                Revista revista = new Revista(txtVolumen.getText(), txtNumero.getText(), mes, Integer.parseInt(txtCodigo.getText()), txtTitulo.getText(), txtAutor.getText(), txtEditorial.getText(), txtAnio.getText());
                if (daoR.agregar(revista)) {
                    mensaje("Revista agregada!");
                } else {
                    mensaje("La revista no se pudo agregar!");
                }
            } catch (Exception e) {
                mensaje("Ingrese datos válidos");
            }
        }
    }//GEN-LAST:event_btnIngresarActionPerformed


    public void cargarCboDocumento() {
        List<TipoDocumento> listaTipoDocumentos = new ArrayList<>();
        TipoDocumentoDAO dao = new TipoDocumentoDAO();
        listaTipoDocumentos = dao.listar();
        for (TipoDocumento x : listaTipoDocumentos) {
            cboTipoDocumento.addItem(x.getDescripcion());
        }
    }

    public void bloquearCampos() {
        // Bloquear todos los campos de LIBRO y REVISTA
        this.txtVolumen.setEnabled(false);
        this.txtNumero.setEnabled(false);
        this.cboMes.setEnabled(false);
        this.rbtnNo.setEnabled(false);
        this.rbtnSi.setEnabled(false);
    }

    public void habilitarCamposLibro() {
        this.rbtnNo.setEnabled(true);
        this.rbtnSi.setEnabled(true);
    }

    public void habilitarCamposRevista() {
        this.txtVolumen.setEnabled(true);
        this.txtNumero.setEnabled(true);
        this.cboMes.setEnabled(true);
    }

    public void limpiarCampos() {
        txtCodigo.setText("");
        txtTitulo.setText("");
        txtAutor.setText("");
        txtEditorial.setText("");
        txtAnio.setText("");
        /////
        this.txtVolumen.setText("");
        this.txtNumero.setText("");
        this.cboMes.setSelectedIndex(0);
        this.rbtnNo.setSelected(false);
        this.rbtnSi.setSelected(true);
    }

    public void bloquearBtnAgregar() {
        btnIngresar.setEnabled(false);
    }

    public void habilitarBtnAgregar() {
        btnIngresar.setEnabled(true);
    }

    public void mensaje(String texto) {
        JOptionPane.showMessageDialog(null, texto);
    }

    public void cargarCboMeses() {
        List<Mes> listamMeses = new ArrayList<>();
        MesDAO dao = new MesDAO();
        listamMeses = dao.listar();
        for (Mes x : listamMeses) {
            cboMes.addItem(x.getDescripcion());
        }
    }


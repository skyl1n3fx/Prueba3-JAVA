    private void cboTipoDocumentoItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cboTipoDocumentoItemStateChanged
        // EVENTO CAMBIO EN CBO
        int index = cboTipoDocumento.getSelectedIndex();
        bloquearCampos();
        bloquearBtnAgregar();
        switch (index) {
            case 1:
                // LIBRO
                habilitarCamposLibro();
                habilitarBtnAgregar();
                break;
            case 2:
                habilitarCamposRevista();
                habilitarBtnAgregar();
                break;
            default:
                break;
        }
    }//GEN-LAST:event_cboTipoDocumentoItemStateChanged

